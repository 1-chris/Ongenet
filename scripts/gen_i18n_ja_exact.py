def main() -> None:
    lines = SRC.read_text(encoding="utf-8").strip().split("\n")
    english = [ast.literal_eval(line) for line in lines]
    assert len(english) == 940, f"Expected 940 strings, got {len(english)}"

    missing = [s for s in english if s not in TRANSLATIONS]
    if missing:
        print(f"MISSING {len(missing)} translations:")
        for s in missing:
            print(repr(s))
        raise SystemExit(1)

    extra = set(TRANSLATIONS) - set(english)
    if extra:
        print(f"WARNING: {len(extra)} extra keys not in source")

    result = {s: TRANSLATIONS[s] for s in english}
    OUT.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(result)} entries to {OUT}")


